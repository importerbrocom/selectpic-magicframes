/**
 * Renders the studio's social icons. Always shows the four brand icons; each
 * links to the URL configured in Settings, falling back to the main site.
 */
export function SocialIcons({ className = '' }: SocialIconsProps) {
  const links = loadSocialLinks();
  return (
    <div className={'socials ' + className}>
      {SOCIAL_ICONS.map((icon) => (
        <a
          key={icon.key}
          className="social"
          href={links[icon.key].trim() || FALLBACK}
          title={icon.label}
          aria-label={icon.label}
          target="_blank"
          rel="noopener noreferrer"
        >
          <Glyph name={icon.key} />
        </a>
      ))}
    </div>
  );
}
